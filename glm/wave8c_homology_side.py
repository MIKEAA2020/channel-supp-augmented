def mat_mul(A, B):
    r, k, c = len(A), len(B), len(B[0])
    assert len(A[0]) == k
    return [[sum(A[i][t] * B[t][j] for t in range(k)) for j in range(c)]
            for i in range(r)]

def snf_diag(A):
    """Smith normal form diagonal (with divisibility) of integer matrix A.
    Returns the list of nonzero diagonal entries d1 | d2 | ... ."""
    r = len(A); c = len(A[0]) if r else 0
    D = [row[:] for row in A]
    rr = cc = 0
    while rr < r and cc < c:
        best = None
        for i in range(rr, r):
            for j in range(cc, c):
                if D[i][j] != 0 and (best is None or abs(D[i][j]) < abs(best[2])):
                    best = (i, j, D[i][j])
        if best is None:
            break
        i0, j0, _ = best
        D[i0], D[rr] = D[rr], D[i0]
        for row in D:
            row[j0], row[cc] = row[cc], row[j0]
        changed = True
        while changed:
            changed = False
            for i in range(rr + 1, r):
                if D[i][cc] != 0:
                    q = D[i][cc] // D[rr][cc]
                    if q:
                        D[i] = [a - q * b for a, b in zip(D[i], D[rr])]
                    if D[i][cc] != 0:
                        D[i], D[rr] = D[rr], D[i]
                        changed = True
                        break
            if changed:
                continue
            for j in range(cc + 1, c):
                if D[rr][j] != 0:
                    q = D[rr][j] // D[rr][cc]
                    if q:
                        for k2 in range(r):
                            D[k2][j] -= q * D[k2][cc]
                    if D[rr][j] != 0:
                        for k2 in range(r):
                            D[k2][j], D[k2][cc] = D[k2][cc], D[k2][j]
                        changed = True
                        break
            if changed:
                continue
            for i in range(rr + 1, r):
                for j in range(cc + 1, c):
                    if D[i][j] != 0 and D[i][j] % D[rr][cc] != 0:
                        D[rr] = [a + b for a, b in zip(D[rr], D[i])]
                        changed = True
                        break
                if changed:
                    break
        if D[rr][cc] < 0:
            D[rr] = [-a for a in D[rr]]
        rr += 1; cc += 1
    diag = [D[i][i] for i in range(min(r, c)) if D[i][i] != 0]
    for a, b in zip(diag, diag[1:]):
        assert b % a == 0, "SNF divisibility failed"
    return diag, r - len(diag) if False else None  # (diag,) placeholder

def snf(A):
    d, _ = snf_diag(A)
    rank = len(d)  # rank of the lattice generated by rows (if rows are indep...)
    return d

def lattice_rank(gens):
    """Rank of the subgroup of Z^n generated by the given integer vectors."""
    if not gens:
        return 0
    A = [list(g) for g in gens]
    d = snf(A)
    return len(d)

def reduce_basis(gens):
    """Hermite-style reduction: an equivalent basis (as row list) of the
    lattice generated by gens (n-dimensional ambient)."""
    n = len(gens[0]) if gens else 0
    rows = [list(g) for g in gens]
    basis = []
    for col in range(n):
        # find gcd-reduced combination with nonzero col entry among remaining rows
        while True:
            piv = [i for i in range(len(rows)) if rows[i][col] != 0]
            if len(piv) <= 1:
                break
            piv.sort(key=lambda i: abs(rows[i][col]))
            i0 = piv[0]
            for i in piv[1:]:
                q = rows[i][col] // rows[i0][col]
                rows[i] = [a - q * b for a, b in zip(rows[i], rows[i0])]
        piv = [i for i in range(len(rows)) if rows[i][col] != 0]
        if piv:
            i0 = piv[0]
            v = rows.pop(i0)
            if v[col] < 0:
                v = [-a for a in v]
            basis.append(v)
            # eliminate this column from remaining rows (already zero by loop)
    return basis

def solve_in_basis(basis, v):
    """Express v as rational combination of the basis rows. Returns list of
    Fractions or None if not in the rational span."""
    r = len(basis); n = len(v)
    if r == 0:
        return [] if all(x == 0 for x in v) else None
    M = [[Fraction(basis[i][j]) for j in range(n)] + [Fraction(v[i])]
         for i in range(r)]
    # Gaussian elimination on the transpose: solve x^T * B = v
    # Instead: build B^T x = v: columns of B^T are the basis vectors.
    # Solve B x = v with B: r x n. Use normal equations via elimination on
    # the augmented matrix [B^T | v^T] with x unknown (n-dim), but x has
    # support only in r dims if basis is a true basis: general rational
    # least-squares-free solve: use r x n system B x = v -> pick r pivot cols.
    # Simpler: transpose approach: B^T is n x r; solve B^T y = v.
    BT = [[Fraction(basis[i][j]) for i in range(r)] for j in range(n)]
    aug = [row[:] + [Fraction(v[j])] for j, row in enumerate(BT)]
    piv_cols = []
    row_i = 0
    for col in range(r):
        p = None
        for i in range(row_i, n):
            if aug[i][col] != 0:
                p = i; break
        if p is None:
            continue
        aug[row_i], aug[p] = aug[p], aug[row_i]
        pv = aug[row_i][col]
        aug[row_i] = [x / pv for x in aug[row_i]]
        for i in range(n):
            if i != row_i and aug[i][col] != 0:
                f = aug[i][col]
                aug[i] = [a - f * b for a, b in zip(aug[i], aug[row_i])]
        piv_cols.append(col)
        row_i += 1
        if row_i == n:
            break
    # check consistency
    for i in range(row_i, n):
        if aug[i][r] != 0 and all(aug[i][k] == 0 for k in range(r)):
            return None  # inconsistent
    y = [Fraction(0)] * r
    for idx, col in enumerate(piv_cols):
        y[col] = aug[idx][r]
    # verify
    for j in range(n):
        s = sum(Fraction(basis[i][j]) * y[i] for i in range(r))
        if s != Fraction(v[j]):
            return None
    return y

def quotient_group(K_basis, L_gens):
    """K/L for lattices L <= K <= Z^n given by a basis of K and generators of
    L. Returns (free_rank, tors) where tors = list of invariant factors."""
    r = len(K_basis)
    if r == 0:
        return (0, [])
    coords = []
    for g in L_gens:
        y = solve_in_basis(K_basis, g)
        assert y is not None, "generator not in K -- invalid input"
        assert all(x.denominator == 1 for x in y), "non-integral coordinate"
        coords.append([int(x) for x in y])
    if not coords:
        return (r, [])
    d = snf(coords)
    # free part: columns not covered
    rankL = lattice_rank(coords)
    free = r - rankL
    # drop 1's from torsion (they contribute trivial factors)
    tors = [x for x in d if x != 1]
    return (free, tors)

def coker_group(A):
    """Z^n / im(A) for an n-column integer matrix (columns = generators).
    Returns (free, tors)."""
    n = len(A)
    gens = [[A[i][j] for i in range(n)] for j in range(n)]  # columns as vectors
    basis = reduce_basis(gens)
    if not basis:
        return (n, [])
    d = snf(basis)
    tors = [x for x in d if x != 1]
    return (n - len(d), tors)

def kernel_basis(A):
    """Basis of ker(A) cap Z^n as row vectors (A square integer matrix)."""
    n = len(A)
    # solve A x = 0: use SNF-free approach: rational RREF then integer lift
    import copy
    M = [row[:] for row in A]
    # augment with identity to track column ops is messy; do direct nullspace
    rows = [list(map(Fraction, row)) for row in M]
    piv = []
    r = 0
    for c in range(n):
        p = None
        for i in range(r, len(rows)):
            if rows[i][c] != 0:
                p = i; break
        if p is None:
            continue
        rows[r], rows[p] = rows[p], rows[r]
        pv = rows[r][c]
        rows[r] = [x / pv for x in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c] != 0:
                f = rows[i][c]
                rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
        piv.append(c)
        r += 1
    free_cols = [c for c in range(n) if c not in piv]
    ker = []
    for fc in free_cols:
        v = [Fraction(0)] * n
        v[fc] = Fraction(1)
        for idx, pc in enumerate(piv):
            v[pc] = -rows[idx][fc]
        # integer lift: entries are already integers? not necessarily.
        vec = [int(x) if x.denominator == 1 else x for x in v]
        assert all(x.denominator == 1 for x in vec if isinstance(x, Fraction)), \
            "non-integral kernel vector -- algorithm bug"
        ker.append([int(x) for x in vec])
    if not ker:
        return []
    return reduce_basis(ker)

def image_gens(A):
    """Generators (columns) of im(A) as integer vectors."""
    n = len(A)
    return [[A[i][j] for i in range(n)] for j in range(n)]

def mat_N(A, m):
    n = len(A)
    N = [[0] * n for _ in range(n)]
    P = [[1 if i == j else 0 for j in range(n)] for i in range(n)]
    for _ in range(m):
        N = [[N[i][j] + P[i][j] for j in range(n)] for i in range(n)]
        P = mat_mul(P, A)
    return N

def mat_sub_I(A):
    return [[A[i][j] - (1 if i == j else 0) for j in range(len(A))]
            for i in range(len(A))]

def gstr(free, tors):
    s = ""
    if free:
        s += f"Z^{free}" if free > 1 else "Z"
    if tors:
        t = " + ".join(f"Z/{x}" for x in tors)
        s += (" x " if s else "") + t if False else (" + " + t if s else t)
    return s if s else "0"

