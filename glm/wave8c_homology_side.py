# orientation character w (g |-> -1) for the Z~-valued SS.
def coinvariant_module(d, k):
    """Degree-k part of Z[x_1..x_d]/(e_1..e_d) with the cyclic variable
    shift matrix, in the descent basis {a_i <= d-1-i}.  Exact integer math."""
    from itertools import combinations
    all_mons = []
    def rec(i, rem, acc):
        if i == d:
            if rem == 0:
                all_mons.append(tuple(acc))
            return
        for v in range(rem + 1):
            rec(i + 1, rem - v, acc + [v])
    rec(0, k, [])
    idx = {m: i for i, m in enumerate(all_mons)}
    N = len(all_mons)
    # relations: e_j * (monomials of degree k-j), each as ONE summed vector
    rel_vecs = []
    for j in range(1, min(d, k) + 1):
        base = []
        def rec2(i, rem, acc):
            if i == d:
                if rem == 0:
                    base.append(tuple(acc))
                return
            for v in range(rem + 1):
                rec2(i + 1, rem - v, acc + [v])
        rec2(0, k - j, [])
        for bm in base:
            vec = [0] * N
            for S in combinations(range(d), j):
                ex = list(bm)
                for i in S:
                    ex[i] += 1
                ex = tuple(ex)
                if ex in idx:
                    vec[idx[ex]] += 1
            if any(vec):
                rel_vecs.append(vec)
    L = reduce_basis(rel_vecs) if rel_vecs else []
    std = [m for m in all_mons if all(m[i] <= d - 1 - i for i in range(d))]
    # sanity: descent count = Mahonian rank
    rank = len(std)
    # the relation lattice must have corank = rank
    # (rank of L as a subgroup of Z^N):
    rl = lattice_rank(L) if L else 0
    assert N - rl == rank, f"descent basis mismatch: N={N}, rankL={rl}, std={rank}"

    def solve_cols(cols, vec):
        n = len(vec); r = len(cols)
        M = [[Fraction(cols[j][i]) for j in range(r)] + [Fraction(vec[i])]
             for i in range(n)]
        piv = []
        row_i = 0
        for col in range(r):
            p = None
            for i in range(row_i, n):
                if M[i][col] != 0:
                    p = i; break
            if p is None:
                continue
            M[row_i], M[p] = M[p], M[row_i]
            pv = M[row_i][col]
            M[row_i] = [x / pv for x in M[row_i]]
            for i in range(n):
                if i != row_i and M[i][col] != 0:
                    f = M[i][col]
                    M[i] = [a - f * b for a, b in zip(M[i], M[row_i])]
            piv.append(col); row_i += 1
        for i in range(row_i, n):
            if M[i][r] != 0 and all(M[i][t] == 0 for t in range(r)):
                raise AssertionError("no solution in solve_cols")
        x = [Fraction(0)] * r
        for ridx, col in enumerate(piv):
            x[col] = M[ridx][r]
        for i in range(n):
            s = sum(x[j] * cols[j][i] for j in range(r))
            if s != Fraction(vec[i]):
                raise AssertionError("bad solve in solve_cols")
        assert all(v.denominator == 1 for v in x), "non-integral reduction"
        return [int(v) for v in x]

    def reduce_to_std(vec):
        cols = []
        for m in std:
            v = [0] * N
            v[idx[m]] = 1
            cols.append(v)
        cols = cols + [list(l) for l in L]
        coeffs = solve_cols(cols, vec)
        return coeffs[:len(std)]

    def shift_mon(m):
        return tuple([m[-1]] + list(m[:-1]))  # x_i -> x_{i+1}: exponents rotate

    A = [[0] * rank for _ in range(rank)]
    for i, m in enumerate(std):
        sm = shift_mon(m)
        v = [0] * N
        v[idx[sm]] = 1
        coeffs = reduce_to_std(v)
        for j, c in enumerate(coeffs):
            A[j][i] = c
    P = A
    for _ in range(d - 1):
        P = mat_mul(P, A)
    assert P == [[1 if i == j else 0 for j in range(rank)] for i in range(rank)], \
        f"shift^{d} != I on degree {k}"
    return A, std

