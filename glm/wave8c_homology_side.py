def cyc_hom(A, m, maxp):
    n = len(A)
    AmI = mat_sub_I(A)
    N = mat_N(A, m)
    # invariants: im(N) <= ker(A-I), im(A-I) <= ker(N)
    kB = kernel_basis(AmI)
    for g in image_gens(N):
        y = solve_in_basis(kB, g) if kB else None
        if kB:
            assert y is not None, "im(N) not in ker(A-I)!"
    kN = kernel_basis(N)
    for g in image_gens(AmI):
        if kN:
            y = solve_in_basis(kN, g)
            assert y is not None, "im(A-I) not in ker(N)!"
    out = []
    for p in range(maxp + 1):
        if p == 0:
            out.append(coker_group(AmI))
        elif p % 2 == 1:
            out.append(quotient_group(kB, image_gens(N)) if kB else (0, []))
        else:
            out.append(quotient_group(kN, image_gens(AmI)) if kN else (0, []))
    return out

def cyc_coh(A, m, maxp):
    n = len(A)
    AmI = mat_sub_I(A)
    N = mat_N(A, m)
    kB = kernel_basis(AmI)
    kN = kernel_basis(N)
    out = []
    for p in range(maxp + 1):
        if p == 0:
            out.append((len(kB), []))
        elif p % 2 == 1:
            out.append(quotient_group(kN, image_gens(AmI)) if kN else (0, []))
        else:
            out.append(quotient_group(kB, image_gens(N)) if kB else (0, []))
    return out

